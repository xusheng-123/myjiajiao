#!/usr/bin/env node
/**
 * Cloudflare Pages 构建前置脚本 — 把 NURTURE_API_HOST 注入 Angular 生产环境文件。
 *
 * 用法（Pages 项目 Build Command 配置为 `npm run build:pages`）：
 *   构建环境变量 NURTURE_API_HOST = api.example.com   （生产）
 *                    NURTURE_API_HOST = api-staging.example.com （Staging）
 * 脚本重写 src/environments/environment.production.ts → fileReplacements 在
 * production configuration 下生效。未设置该变量时写入同源回退值并告警。
 * 域名只进构建产物，不进源码。
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src', 'environments', 'environment.production.ts');

const raw = (process.env.NURTURE_API_HOST || '').trim();
let host = raw.replace(/^https?:\/\//i, '').replace(/\/+$/, '');
if (raw && !host) {
  console.error('[write-env] NURTURE_API_HOST 解析失败：' + raw);
  process.exit(1);
}

const apiBaseUrl = host ? `https://${host}/api` : '/api';
if (!host) {
  console.warn(
    '[write-env] 未设置 NURTURE_API_HOST，使用同源回退 /api —— 仅适用于 Pages + 同域反代形态；' +
      '跨源 Pages + Tunnel 架构必须在 Pages 构建变量中提供该值。',
  );
}

const content = `/* AUTOMATICALLY GENERATED by scripts/write-env.mjs — do not edit; build-time: ${new Date().toISOString()} */
export const environment = {
  production: true,
  apiBaseUrl: '${apiBaseUrl}',
};
`;
writeFileSync(target, content, 'utf-8');
console.log(`[write-env] environment.production.ts -> apiBaseUrl='${apiBaseUrl}'`);
